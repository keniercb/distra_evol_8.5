    public function uploaderPackagesRepositories($password, $dirPackages, $nombreImg)
    {
        $resultado = array();
        $uploaddir = dirname(__FILE__) . '/../../../../web/package/resources/tmp/';
        $arraysRepo = json_decode(
            file_get_contents(
                dirname(__FILE__) . '/../../../../apps/package/comun/recursos/json/svn_composer.json'
            ),
            true
        );
        $direccionRepo = $arraysRepo["file"];
        if (file_exists($dirPackages)) {
            $base = basename($dirPackages);
            $type = explode('.', $base);
            $length = count($type);
            if ($type[$length - 1] == 'zip') {
                $random = time();
                $namePackages = basename($dirPackages);
                $file = $uploaddir . $namePackages;
                mkdir($uploaddir . "$random");
                shell_exec(
                    'cd ' . $uploaddir . '; unzip ' . $namePackages . " -d " . $uploaddir . "$random"
                );
                $carpeta = "";
                $directorio = opendir($uploaddir . "$random");
                while ($actual = readdir($directorio)) {
                    if ($actual != "." && $actual != ".." && $actual != '.svn'
                    ) {
                        $carpeta = $actual;
                    }
                }
                $datos = json_decode(
                    file_get_contents(
                        $uploaddir . "$random/$carpeta/composer.json"
                    ),
                    true
                );
                //verificacion de autenticidad
                //obtengo el usuario logueado
                $user = $this->global->perfil->usuario;
                //extrigo la clave privada
                $tmpPass = $uploaddir . "$random/tmp.txt";
                $archivo = fopen($tmpPass, "a");
                fwrite($archivo, $password);
                fclose($archivo);
                $config = json_decode(
                    file_get_contents(
                        dirname(__FILE__) . "/../../comun/recursos/json/svn_composer.json"
                    ),
                    true
                );
                $llavePublica = $config['llave_publica'];
                $dirLlavePublica = $direccionRepo . '/' . $llavePublica;
                $dirLavePrivada = dirname(__FILE__) . '/../../comun/recursos/clave_privada';
                shell_exec(
                    "openssl pkcs12 -in $dirLavePrivada/$user.p12 -nocerts " .
                    "-nodes -password file:$tmpPass -out " . "$dirLavePrivada/$random.pem"
                );
                if (is_file("$dirLavePrivada/$random.pem") && filesize("$dirLavePrivada/$random.pem") != 0
                ) {
                    /*el $uploaddir es el directorio de la llave publica*/
                    if (!file_exists("$dirLlavePublica/$user.pem")) {
                        /*fin*/
                        shell_exec(
                            "openssl pkcs12 -in $dirLavePrivada/$user.p12 -clcerts " .
                            "-nokeys -password file:$tmpPass -out " . "$dirLlavePublica/$user.pem"
                        );
                    }
                    mkdir($uploaddir . $random . "pack");
                    $mcd = "openssl dgst -sha1 -sign $dirLavePrivada/$random.pem " . "-out $uploaddir/$random" .
                        "pack/signature.sig $file";
                    shell_exec($mcd);
                    shell_exec(
                        "mv " . $uploaddir . "" . $namePackages . " " . $uploaddir . $random . "pack"
                    );
                    //Comprimimos el archivo nuevamente
                    shell_exec(
                        'cd ' . $uploaddir . ";zip -r -m -j " . "./$random.zip" . " ./$random" . "pack/*"
                    );
                    //Eliminamos la carpeta temporal
                    shell_exec("rm -R -f $uploaddir/$random/");
                    shell_exec("rm -R -f $uploaddir/$random" . "pack/");
                    //eliminamos la clave privada
                    unlink("$dirLavePrivada/$random.pem");
                    $checksum = hash_file('sha1', $uploaddir . "$random.zip");
                    $tmp = array(
                        'url' => $arraysRepo['url'] . "/$random.zip",
                        'type' => 'zip',
                        'shasum' => $checksum
                    );
                    $datos['dist'] = $tmp;
                    $localPackages = json_decode(
                        file_get_contents($direccionRepo . '/packages.json', null, $this->getContextOptions()),
                        true
                    );
                    $arrays = array(
                        'liberado' => false
                    );
                    $datos['extra']['visible'] = $arrays;
                    $localPackages['packages'][$datos['name']][$datos['version']] = $datos;
                    if (file_put_contents(
                        $direccionRepo . '/packages.json',
                        json_encode($localPackages)
                    )) {
                        $util = new UtilFunctionModel();
                        $util->copy($uploaddir . "$random.zip", $direccionRepo);
                        $util->copy(
                            $uploaddir . 'logos/' . $nombreImg,
                            $direccionRepo . "/logos/"
                        );
                        unlink($uploaddir . $random . '.zip');
                        $msg = 'El paquete ha sido creado satisfactoriamente.';
                        $resultado = array(
                            'success' => true,
                            'message' => $msg
                        );
                    } else {
                        unlink("$dirLavePrivada/$random.pem");
                        unlink($uploaddir . $random . '.zip');
                        throw new Exception(
                            'No se pudo actualizar el repositorio.'
                        );
                    }
                } else {
                    unlink("$dirLavePrivada/$random.pem");
                    shell_exec("rm -R -f $uploaddir/$random/");
                    unlink($uploaddir . "" . $namePackages);
                    $msg = 'La contraseña introducida no desbloquea el
                     certificado. Verifique por favor.';
                    throw new Exception(
                        $msg
                    );
                }
            } else {
                throw new Exception(
                    'El archivo introducido no es v&aacute;lido.'
                );
            }
        } else {
            throw new Exception('No se pudo crear el paquete.');
        }

        return $resultado;
    }

    public function releasePackages($arraysParameters)
    {
        $arraysPackages = json_decode($arraysParameters['arrayDatos'], true);
        /*la dir del repositorio leerla del fichero de configuracion*/
        $arraysRepos = json_decode(
            file_get_contents(
                dirname(__FILE__) . '/../../../../apps/package/comun/recursos/json/svn_composer.json'
            ),
            true
        );
        $direccionRepo = $arraysRepos["file"];//direcion dinamica del repo local
        $dirRepoLocal = $direccionRepo;
        $contenido = json_decode(
            file_get_contents($dirRepoLocal . '/packages.json', null, $this->getContextOptions()),
            true
        );
        foreach ($arraysPackages as $idPackage) {
            $arrays = $this->getTagsPackages($idPackage);
            $contenido['packages'][$arrays['name']]
            [$arrays['version']]['extra']['visible']['liberado'] = true;
        }
        if (file_put_contents(
            $dirRepoLocal . '/packages.json',
            json_encode($contenido)
        )) {
            if(count($arraysPackages) == 1)
                $msg = 'El paquete ha sido publicado satisfactoriamente.';
            else
                $msg = 'Los paquetes han sido publicados satisfactoriamente.';

//            $msg = 'El(Los) paquete(s) ha(n) sido publicados(s)
//            satisfactoriamente.';

            return array(
                'success' => true,
                'message' => $msg
            );
        }
        $msg = 'No se pudo actualizar el repositorio.';

        return array(
            'success' => false,
            'message' => $msg
        );
    }

    public function isTagsPackages($tags)
    {
        $listPackages = $this->getPackagesRepositories();
        foreach ($listPackages['datos'] as $package) {
            if ($package['id'] == $tags) {
                return true;
            }
        }

        return false;
    }

    private function getTagsPackages($tags)
    {

        $listPackages = $this->getPackagesRepositories();
        foreach ($listPackages['datos'] as $key => $package) {
            if ($package['id'] == $tags) {
                return array(
                    'name'    => $package['name'],
                    'version' => $package['version'],
                    'logo'    => $package['logo'],
                    'url'     => $package['url']
                );
            }
        }

        return false;

    }

