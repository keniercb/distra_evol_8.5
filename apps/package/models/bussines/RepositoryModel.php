            if (count($contenido['packages'][$arrays['name']]) == 0) {
                unset($contenido['packages'][$arrays['name']]);
            }
            $logo = basename($arrays['logo']);
            $fichero = basename($arrays['url']);
            if ($logo != 'zeolides.png') {
                unlink($dirRepoLocal . '/logos/' . $logo);
            }
            unlink($dirRepoLocal . '/' . $fichero);
        }
        if (file_put_contents(
            $dirRepoLocal . '/packages.json',
            json_encode($contenido)
        )) {
            if(count($arraysPackages) == 1)
                $msg = 'El paquete ha sido eliminado satisfactoriamente.';
            else
                $msg = 'Los paquetes han sido eliminados satisfactoriamente.';
//            $msg = 'El(Los) paquete(s) ha(n)
//          sido eliminado(s) satisfactoriamente.';
            return array(
                'success' => true,
                'message' => $msg
            );
        }

        return array(
            'success' => false,
            'message' => 'No se pudo actualizar el repositorio'
        );
    }

