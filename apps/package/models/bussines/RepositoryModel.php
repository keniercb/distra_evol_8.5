                                "success" => false,
                                "message" => $msg
                            );
                        }
                    } else {
                        $msg = "El limite maximo del archivo es " . ini_get("upload_max_filesize") . " MB.";
                        return array(
                            "success" => false,
                            "message" => $msg
                        );
                    }
