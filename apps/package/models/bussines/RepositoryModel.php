    public function isAuthenticate($idNode)
    {
        $session = new Zend_Session_Namespace('repositories');
        $arrays = $session->repositories;
        if (isset($arrays[$idNode]) && $arrays[$idNode]['user'] != '' && $arrays[$idNode]['password']
        ) {
            return true;
        }

        return false;
    }

    public function authenticateCorrect($arraysParameters)
    {
        $svn = new ManagerSVNModel();
        $url = $arraysParameters['url'];
        $url = ($url[strlen($url) - 1] == '/') ? $url : $url . '/';
        $user = $arraysParameters['user'];
        $password = $arraysParameters['password'];
        $idpadre = $arraysParameters['idpadre'];
        $result = $svn->svnList($url, $user, $password);
        if ($result) {
            $isRepo = false;
            foreach ($result as $value) {
                if ($value == 'tags') {
                    $isRepo = true;
                }
            }
            $arrays = array();
            if ($isRepo) {
                $result = $svn->svnList($url . 'tags', $user, $password);
                if (is_array($result)) {
                    Zend_Session::start();
                    $session = new Zend_Session_Namespace('repositories');
                    $arrays = $session->repositories;
                    $arrays[$idpadre] = array(
                        "user" => $user,
                        "password" => $password
                    );
                    $session->repositories = $arrays;

                    return array(
                        'success' => true,
                        'message' => 'Autenticación correcta.',
                    );
                }
            } else {
                return array(
                    'success' => false,
                    'message' => 'El repositorio no esta bien configurado',
                );
            }
        }
        $msg = 'El usuario no tiene acceso al repositorio.
         Introduzca nuevamente los datos.';

        return array(
            'success' => false,
            'message' => $msg
        );
    }

