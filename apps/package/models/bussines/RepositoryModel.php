    public function getRequire($arraysParameters)
    {
        $sessionOne = new Zend_Session_Namespace('repositories');
        $arrays = $sessionOne->repositories;
        $svn = new ManagerSVNModel();
        $idpadre = $arraysParameters['idpadre'];
        $user = $arrays[$idpadre]['user'];
        $password = $arrays[$idpadre]['password'];
        $url = $arraysParameters['url'];
        $url = ($url[strlen($url) - 1] == '/')
            ? $url . "tags/" . $arraysParameters['nameTags'] : $url . '/tags/' . $arraysParameters['nameTags'];
        $texto = $svn->svnExternals($url, $user, $password);
        $tmpArrays = explode(chr(10), $texto);
        $require = array();
        foreach ($tmpArrays as $line) {
            $tmp = explode(" ", $line);
            $http = "";
            $apps = "";
            if (substr($tmp[0], 0, 4) == 'http') {
                $http = $tmp[0];
                $apps = $tmp[1];
            } else {
                if (substr($tmp[1], 0, 4) == 'http') {
                    $http = $tmp[1];
                    $apps = $tmp[0];
                }
            }
            $pUrl = explode('/tags/', $http);
            $util = new UtilFunctionModel();
            if (count($pUrl) == 2 && substr($apps, 0, 4) == 'apps') {
                $vUrl = explode('/', $pUrl[1]);
                $nameTags = $vUrl[0];
                $name = $util->getNameByUrl($pUrl[0]);
                array_push(
                    $require,
                    array(
                        'nameTags' => $nameTags,
                        'version' => $util->getVersionByTags($nameTags),//todo: aki arreglar la version
                        'typeVersion' => $util->getVersionType($nameTags),
                        'name' => str_replace('_', "", $name),
                        'url' => $pUrl[0]
                    )
                );
            }
        }

        return $require;
    }

