<?php

class UtilFunctionModel extends ZendExt_Model
{

    public function UtilFunctionModel()
    {
        parent::ZendExt_Model(); // TODO: Change the autogenerated stub
    }

    public function generateJsonComposer($dirname, $array, $nameJson)
    {
        file_put_contents(
            $dirname . '/' . $nameJson . '.json', json_encode($array)
        );
    }

    public function generateFiles($dirName)
    {
        $dirJson
            = dirname(__FILE__) . '/../../comun/recursos/json/generate.json';
        $arrays = json_decode(file_get_contents($dirJson), true);
        $this->generate($dirName, $arrays['directory']);
    }

    public function generate($dirName, $arrays)
    {
        foreach ($arrays as $value) {
            if (isset($value['name'])) {
                $newDirName = $dirName . '/' . $value['name'];
                mkdir($newDirName, 0777);
                if (isset($value['directory'])) {
                    $this->generate($newDirName, $value['directory']);
                }
            }
        }
    }

    public function compresZip($dirName, $namefile, $nameZip)
    {
        shell_exec(
            'cd ' . $dirName . '; zip -r ' . $nameZip . '.zip ' . $namefile
        );
    }

    public function deleteDirectory($fileName, $recursive = true)
    {
        $cmd = ($recursive) ? "rm -R $fileName" : "rm $fileName";
        $result = shell_exec($cmd);
        if ($result != null) {
            return true;
        }

        return false;
    }

    /**Los numeros 7,8,9 conrresponden a alfa, beta, RC respectivamente**/
    public function getVersionType($tagsName)
    {
        $types = array('Alfa', 'Beta', 'RC');
        foreach ($types as $type){
            $pos = strpos($tagsName, $type);
            if(!$pos)
                $pos = strpos($tagsName, strtoupper($type));
            if ($pos !== false) {
                if($type == 'Alfa'){
                    return '7';
                }
                return ($type == 'RC') ? '9' : '8';
            }
        }
    }

    public function getVersionByTags($tagsName)
    {
        $patern = '/^[1-9]+.[0-9]+.[0-9]+.[0-9]+/';
        for ($i = 0; $i < strlen($tagsName); $i++) {
            preg_match(
                $patern, substr($tagsName, $i), $coincidencias,
                PREG_OFFSET_CAPTURE
            );
            if (count($coincidencias) > 0) {
                return $this->getVersionType($tagsName) . $coincidencias[0][0];
            }
        }

        return false;
    }

    public function copy($origen, $destino, $recursive = false)
    {
        $cmd = "cp $origen $destino";
        if ($recursive) {
            $cmd = "cp -R $origen $destino";
        }
        shell_exec($cmd);
    }

    public function getType($file)
    {
        $type = explode('.', $file);

        return $type[count($type) - 1];
    }

    public function getNameFile($file)
    {
        $type = explode('.', $file);

        return $type[0];
    }

    public function scanDirectory($directory)
    {
        return array_diff(scandir($directory), array('.', '..', '.svn'));
    }

    public function getDirectory($arraysDirectory, $pos)
    {
        $arrays = array();
        $i = 0;
        foreach ($arraysDirectory as $value) {
            if ($i < $pos) {
                $arrays[$i++] = $value;
            }
        }

        return $arrays;
    }

    public function ofuscarPhp($dirModule)
    {
        if (is_dir($dirModule)) {
            $params["fuente"] = $dirModule;
            $xwriter = new Xcompiler\Xwriter();
            $xwriter->compile_dir($params);
        }
    }

    public function getNameByUrl($url)
    {
        return basename($url);
    }

}