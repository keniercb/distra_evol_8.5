class UtilModel extends ZendExt_Model
{

    public function UtilMode7l()
    {
        parent::ZendExt_Model(); // TODO: Change the autogenerated stub
    }
    static public function searchRepositories($arraysRepositories, $url)
    {
        foreach ($arraysRepositories as $vUrl) {
            if ($vUrl['url'] == $url) {
                return true;
            }
        }

        return false;
    }

    static public function getPostRepository($arraysRepositories, $url)
    {
        $length = count($arraysRepositories['repositories']);
        for ($i = 0; $i < $length; $i++) {
            if ($arraysRepositories['repositories'][$i]['url'] == $url) {
                return $i;
            }
        }

        return -1;
    }

    static public function getDependencyByPackages($arraysTags)
    {
        $result = array();
        foreach ($arraysTags as $tags) {//todo: add this cod      ". '-' . $tags['typeVersion']]"
            $result['xetid/' . $tags['name']] = "=" . $tags['version'];
        }

        return $result;
    }

    static public function getDependencyAcercaDe($arraysTmpRequire)
    {
        $result = array();
        $cadena = "";
        $length = count($arraysTmpRequire);
        $i = 1;
        foreach ($arraysTmpRequire as $tags) {
            if ($i++ < $length) {
                $cadena .= $tags['name'] . ' ' . $tags['version'] . ',';
            } else {
                $cadena .= $tags['name'] . ' ' . $tags['version'];
            }
        }
        array_push($result, $cadena);

        return $result;
    }

    /**
     * Escribe lo que le pasen a un archivo de logs
     *
     * @param string $cadena texto a escribir en el log
     * @param string $tipo   texto que indica el tipo de mensaje.
     *                       Los valores normales son Info, Error,
     *                       Warn Debug
     * @param string $url
     *                       texto que indica la direccion de donde se lee el fichero
     */
    static public function write_log($url, $cadena, $tipo)
    {
        $arch = fopen($url, "a+");
        fwrite(
            $arch,
            "[" . date("Y-m-d H:i:s.u") . " " . $_SERVER['REMOTE_ADDR'] . " " . $_SERVER['HTTP_X_FORWARDED_FOR'] .
            " - $tipo ] " . $cadena . "\n"
        );
        fclose($arch);
    }

    static public function clear_log($dir)
    {
        $fp = fopen($dir, "w");
        fclose($fp);
    }

} 