---------- Script 1 para actualizar el nuevo valor contable en la tabla temporal para dejar el historial -------
update mod_migracion_aft.tmp_valorresidualnegativo v
set valorresidualactual =sq.valorcalculado, valorresidualnuevo = sq.valorcontable
from
(
select rg.idregnumerico,tmp.nroinventario,rg.valorcontable, rg.depreciacionacumulada, tmp.valorresidualexcel, (rg.valorcontable - rg.depreciacionacumulada) as valorcalculado,
v.denominacion
from mod_migracion_aft.tmp_valorresidualnegativo tmp
inner join mod_logactivofijotangible.dat_regnumericoactivo rg on rg.nroinventario = tmp.nroinventario
inner join mod_logactivofijotangible.dat_registronumerico rn on rn.idregnumerico = rg.idregnumerico
inner join mod_logistica.dat_producto p on p.idproducto = rn.idproducto
inner join mod_estructuracomp.v_dametodasestructuras v on v.idestructura = p.idestructuracomun
group by tmp.nroinventario,rg.valorcontable, rg.depreciacionacumulada, tmp.valorresidualexcel,v.denominacion,rg.idregnumerico
having (rg.valorcontable - rg.depreciacionacumulada) < 0
) as sq
where v.nroinventario = sq.nroinventario;

---------- Script 2 para actualizar el nuevo valor de la depreciacion acumulada en la tabla de dat_regnumericoactivo -------
update mod_logactivofijotangible.dat_regnumericoactivo n
set depreciacionacumulada = sq.valorcontable
from 
(select rg.idregnumerico,tmp.nroinventario,rg.valorcontable, rg.depreciacionacumulada, tmp.valorresidualexcel, (rg.valorcontable - rg.depreciacionacumulada) as valorcalculado,
v.denominacion
from mod_migracion_aft.tmp_valorresidualnegativo tmp
inner join mod_logactivofijotangible.dat_regnumericoactivo rg on rg.nroinventario = tmp.nroinventario
inner join mod_logactivofijotangible.dat_registronumerico rn on rn.idregnumerico = rg.idregnumerico
inner join mod_logistica.dat_producto p on p.idproducto = rn.idproducto
inner join mod_estructuracomp.v_dametodasestructuras v on v.idestructura = p.idestructuracomun
group by tmp.nroinventario,rg.valorcontable, rg.depreciacionacumulada, tmp.valorresidualexcel,v.denominacion,rg.idregnumerico
having (rg.valorcontable - rg.depreciacionacumulada) < 0) as sq
where n.nroinventario = sq.nroinventario;