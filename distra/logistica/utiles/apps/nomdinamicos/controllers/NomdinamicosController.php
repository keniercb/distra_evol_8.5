    $dir = Zend_Registry::getInstance()->get('config')->dir_aplication . '/logistica/utiles/comun/config.php';
    include_once $dir;
    set_include_path(get_include_path() . PATH_SEPARATOR . $config['include_path']);
}

class NomdinamicosController extends BaseController
{
    private $model;

    public function init()
    {
        parent::init('log.lb.nomdinamicos');
        $this->model = new NomdinamicosModel();
    }

    public function nomdinamicosAction()
    {
        $this->autoShow = false;
        $this->controllerConfig = 'log';
        $this->prepareView();
        $this->initComponent('log.lb.nomdinamicos');
        $this->renderTemplate();
    }

    public function cargarNomDinamicosAction()
    {
        $this->objectHelper->synchronize($this, $this->model->cargarNomDinamicos($this->uiParams));
    }

    public function adicionarNomDinamicoAction()
    {
        $datos = Zend_Json::decode($this->uiParams['data']);
        $this->objectHelper->synchronize($this, $this->model->adicionarNomDinamico($datos));
    }

    public function eliminarNomDinamicosAction()
    {
        $idnomecladores = Zend_Json::decode($this->uiParams['id']);
        $this->model->eliminarNomDinamicos($idnomecladores);
    }

    public function savePropiedadesAction()
    {
        $params = $this->_request->GetPost();
        $this->model->savePropiedades($params);
    }

    public function cargarDatosNomAction()
    {
        $this->unsetNullValues();
        /*$this->setDefaultParam('start', 0);
        $this->setDefaultParam('limit', 30);*/
        $this->objectHelper->synchronize($this, $this->model->cargarDatosNom($this->uiParams));
    }

    public function adicionarDatoNomAction()
    {
        $this->uiParams = Zend_Json::decode($this->uiParams['data']);
        $this->model->adicionarDato($this->uiParams);
    }

    public function eliminarDatoNomAction()
    {
        $params = Zend_Json::decode($this->uiParams['id']);
        $this->model->eliminarDato($params);
    }

    public function initComponent($component)
    {
        parent::initComponent($component); // TODO: Change the autogenerated stub
    }

    public function cargarTallasNomAction(){
        $this->unsetNullValues();
        $this->setDefaultParam('start', 0);
        $this->setDefaultParam('limit', 30);
        $this->objectHelper->synchronize($this, $this->model->cargarTallasNom($this->uiParams));
    }

}
